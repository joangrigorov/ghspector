package keymap

import (
	"flag"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

var update = flag.Bool("update", false, "rewrite the generated keybinding reference")

// docPath is the generated reference, relative to this package.
const docPath = "../../docs/keybindings.md"

// TestKeybindingsDocIsCurrent keeps docs/keybindings.md in step with the table.
//
// The README used to carry a hand-written table per view, which is how it ended
// up documenting a Dashboard that does not exist and the reverse of the Jobs
// keys. The reference is now generated here, and this test fails when the two
// drift.
//
// Regenerate with:
//
//	go test ./internal/keymap -update
func TestKeybindingsDocIsCurrent(t *testing.T) {
	want := renderKeybindingsDoc()

	if *update {
		if err := os.WriteFile(docPath, []byte(want), 0o644); err != nil {
			t.Fatalf("failed to write %s: %v", docPath, err)
		}
		return
	}

	got, err := os.ReadFile(filepath.Clean(docPath))
	if err != nil {
		t.Fatalf("failed to read %s (run go test ./internal/keymap -update): %v", docPath, err)
	}
	if string(got) != want {
		t.Errorf("%s is stale; run go test ./internal/keymap -update", docPath)
	}
}

// TestEveryScopeAppearsInTheDoc guards against a scope silently dropping out of
// the generated reference.
func TestEveryScopeAppearsInTheDoc(t *testing.T) {
	doc := renderKeybindingsDoc()
	for _, scope := range Scopes() {
		documented := Documented(scope)
		if len(documented) == 0 {
			continue
		}
		heading := "## " + Title(scope)
		if !strings.Contains(doc, heading) {
			t.Errorf("scope %q is missing heading %q from the reference", scope, heading)
		}
		for _, b := range documented {
			if !strings.Contains(doc, b.Help) {
				t.Errorf("scope %q: binding help %q is missing from the reference", scope, b.Help)
			}
		}
	}
}

// renderKeybindingsDoc renders the reference, grouped by scope in help order.
func renderKeybindingsDoc() string {
	var b strings.Builder
	b.WriteString("<!-- Generated by internal/keymap. Do not edit by hand. -->\n")
	b.WriteString("<!-- Regenerate with: go test ./internal/keymap -update -->\n\n")
	b.WriteString("# Keybindings\n\n")
	b.WriteString("Every binding the application handles, grouped by the scope it is active in.\n")
	b.WriteString("This file is generated from the keymap table, so it cannot drift from the code.\n\n")

	for _, scope := range Scopes() {
		documented := Documented(scope)
		if len(documented) == 0 {
			continue
		}
		b.WriteString("## " + Title(scope) + "\n\n")
		b.WriteString("| Key | Action |\n")
		b.WriteString("| --- | --- |\n")
		for _, binding := range documented {
			keys := "`" + strings.ReplaceAll(KeysFor(binding), "/", "` / `") + "`"
			action := binding.Help
			if binding.Destructive {
				action += " *(changes remote state)*"
			}
			b.WriteString("| " + keys + " | " + action + " |\n")
		}
		b.WriteString("\n")
	}
	return b.String()
}
